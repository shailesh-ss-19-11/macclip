'use strict';
// Adapter over Electron's clipboard / nativeImage. The only file that touches the real pasteboard.
const { clipboard, nativeImage } = require('electron');
const crypto = require('node:crypto');

const THUMB_PX = 192;
const IMAGE_FORMATS = ['public.png', 'public.tiff'];

function rawImageBuffer() {
  const formats = clipboard.availableFormats();
  if (formats.includes('image/png')) return clipboard.readBuffer('public.png');
  if (formats.includes('image/tiff')) return clipboard.readBuffer('public.tiff');
  return null;
}

function formats() {
  // Electron maps well-known types to MIME; custom UTIs (e.g. org.nspasteboard.ConcealedType) pass through.
  const available = clipboard.availableFormats();
  const extra = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType',
    'org.nspasteboard.AutoGeneratedType', 'com.agilebits.onepassword'];
  return [...available, ...extra.filter((f) => !available.includes(f) && clipboard.has(f))];
}

/** Decodes image bytes into { png, thumb, width, height }, or null if they are not an image. */
function processImage(buffer) {
  if (!buffer) return null;
  const img = nativeImage.createFromBuffer(buffer);
  if (img.isEmpty()) return null;
  const { width, height } = img.getSize();
  const thumb = img.resize({ width: width >= height ? Math.min(THUMB_PX, width) : undefined, height: height > width ? Math.min(THUMB_PX, height) : undefined, quality: 'good' });
  return { png: img.toPNG(), thumb: thumb.toPNG(), width, height };
}

module.exports = {
  formats,
  processImage,

  fingerprint() {
    const h = crypto.createHash('md5');
    h.update(clipboard.availableFormats().join('|'));
    h.update('\0');
    h.update(clipboard.readText());
    const img = rawImageBuffer();
    if (img) h.update(img);
    return h.digest('hex');
  },

  snapshot() {
    const available = clipboard.availableFormats();
    const raw = rawImageBuffer();
    const rtf = clipboard.readRTF();
    return {
      text: clipboard.readText(),
      rtf: rtf ? Buffer.from(rtf, 'binary') : null,
      html: clipboard.readHTML() || null,
      hasFileUrl: available.includes('text/uri-list') && clipboard.has('public.file-url'),
      imageByteLength: raw ? raw.length : 0,
      getImage: () => processImage(raw),
    };
  },

  write(item, imageBuffer, { plain = false } = {}) {
    if (item.kind === 'image') {
      if (imageBuffer) clipboard.writeImage(nativeImage.createFromBuffer(imageBuffer));
    } else if (item.kind === 'richText' && !plain) {
      clipboard.write({
        text: item.text ?? '',
        ...(item.rtf ? { rtf: Buffer.from(item.rtf, 'base64').toString('binary') } : {}),
        ...(item.html ? { html: item.html } : {}),
      });
    } else {
      clipboard.writeText(item.text ?? '');
    }
  },
};
